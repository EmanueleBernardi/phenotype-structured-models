% =========================================================================
% PARAMETERS
% Parameters for the numerical simulations of:
% "Derivation and quasi-invariant asymptotics of
%  phenotype-structured integro-differential models"
% E. Bernardi, T. Lorenzi, A. Tosin
% =========================================================================

clear all; close all;

% -------------------------------------------------------------------------
% Net proliferation rate r(v) = (1 - (v - vm)^2) * psi(v)
% -------------------------------------------------------------------------
vm    = 1.5;   % fittest trait (maximum point of r)
R     = 5;     % radius of the mollifier psi
delta = 0.5;   % amplitude of the transition layer of psi

% -------------------------------------------------------------------------
% Quasi-invariant scaling parameters
% -------------------------------------------------------------------------
alpha = -0.3;  % drift coefficient (set to -0.3, 0, or 0.3)
beta  =  0.4;  % diffusion coefficient

% -------------------------------------------------------------------------
% Spatial domain
% -------------------------------------------------------------------------
a = -15;
b =  15;
n = 1199;

% -------------------------------------------------------------------------
% Time domain
% -------------------------------------------------------------------------
Tf = 10; 

% -------------------------------------------------------------------------
% Initial condition: Gaussian with mass rho0, mean v_0, variance 1/s0
% -------------------------------------------------------------------------
rho0 = 0.3;
v_0  = 0;
s0   = 2;

% -------------------------------------------------------------------------
% Monte Carlo
% -------------------------------------------------------------------------
N = 1e5;   % number of agents

% -------------------------------------------------------------------------
% Create data folder if it does not exist and save
% -------------------------------------------------------------------------
if ~exist('../data', 'dir')
    mkdir('../data');
end
save('../data/parameters.mat');